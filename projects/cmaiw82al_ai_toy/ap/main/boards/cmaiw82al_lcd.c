void cmaiw82al_lcd_devices_init(void)
{
    bk_lcd_set_devices_list(s_cmaiw82al_lcd_devices,
        sizeof(s_cmaiw82al_lcd_devices) / sizeof(s_cmaiw82al_lcd_devices[0]));
    LOGI("registered LCD device: %s, 160x160 dual SPI runtime qspi_clk=LCD_QSPI_60M lcd2_reset=GPIO%u lcd1_reset=GPIO%u\r\n",
        CMAIW82AL_LCD_DEVICE_NAME,
        LCD2_RESET_GPIO,
        LCD1_RESET_GPIO);
}
